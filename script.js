const emailReady = Boolean(
  window.emailjs &&
  EMAILJS_SERVICE_ID &&
  EMAILJS_TEMPLATE_ID &&
  EMAILJS_PUBLIC_KEY
);

if (emailReady) {
  try {
    window.emailjs.init({
      publicKey: EMAILJS_PUBLIC_KEY
    });
  } catch (error) {
    console.error('EmailJS initialization error:', error);
  }
}

async function sendRequest({ name, contact, message: requestMessage }, statusNode, button) {
  if (!name || !contact || !requestMessage) {
    setStatus(
      statusNode,
      'Заполни, пожалуйста, обязательные поля.',
      'error'
    );
    return false;
  }

  if (!emailReady) {
    setStatus(
      statusNode,
      'Сервис отправки не загрузился. Обнови страницу и попробуй ещё раз.',
      'error'
    );
    return false;
  }

  const originalButtonText = button
    ? button.textContent.trim()
    : '';

  if (button) {
    button.disabled = true;
    setButtonText(button, message('Отправляем…'));
  }

  setStatus(statusNode, 'Отправляем заявку…', 'pending');

  try {
    await window.emailjs.send(
      EMAILJS_SERVICE_ID,
      EMAILJS_TEMPLATE_ID,
      {
        name,
        contact,
        message: requestMessage
      }
    );

    setStatus(
      statusNode,
      'Заявка отправлена! Спасибо, скоро свяжемся.',
      'success'
    );

    return true;
  } catch (error) {
    console.error('EmailJS send error:', error);

    setStatus(
      statusNode,
      'Не удалось отправить заявку. Проверь подключение и попробуй ещё раз.',
      'error'
    );

    return false;
  } finally {
    if (button) {
      button.disabled = false;
      setButtonText(button, originalButtonText.replace('↗', '').trim());
    }
  }
}

