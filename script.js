const languageSelect = document.getElementById('languageSelect');
const originalTextNodes = new Map();
const originalAttributes = new Map();

function rememberOriginals() {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT
  );

  let node;
  while ((node = walker.nextNode())) {
    if (!originalTextNodes.has(node)) {
      originalTextNodes.set(node, node.nodeValue);
    }
  }

  document.querySelectorAll('[placeholder], [aria-label], [alt], [title]').forEach(element => {
    ['placeholder', 'aria-label', 'alt', 'title'].forEach(attribute => {
      if (element.hasAttribute(attribute)) {
        const key = `${attribute}`;
        if (!originalAttributes.has(element)) {
          originalAttributes.set(element, {});
        }
        if (!(key in originalAttributes.get(element))) {
          originalAttributes.get(element)[key] = element.getAttribute(attribute);
        }
      }
    });
  });
}

function translateText(lang) {
  const dictionary = translations[lang] || translations.ru;

  rememberOriginals();

  // Перевод обычного текста, не удаляя HTML-разметку и иконки.
  originalTextNodes.forEach((original, node) => {
    if (!node.isConnected) return;

    const trimmed = original.trim();
    if (!trimmed) return;

    const translated = dictionary[trimmed];

    if (translated !== undefined) {
      const leading = original.match(/^\s*/)?.[0] || '';
      const trailing = original.match(/\s*$/)?.[0] || '';
      node.nodeValue = leading + translated + trailing;
    } else {
      node.nodeValue = original;
    }
  });

  // Перевод placeholder, alt, title и aria-label.
  originalAttributes.forEach((attributes, element) => {
    if (!element.isConnected) return;

    Object.entries(attributes).forEach(([attribute, original]) => {
      element.setAttribute(attribute, dictionary[original] || original);
    });
  });

  // Заголовок вкладки и описание страницы.
  const pageTitles = {
    ru: 'Центр Блеск — путешествия ближе, чем кажется',
    en: 'Blesk Travel Center — journeys closer than you think',
    zh: 'БЛЕСК 旅行中心 — 探索更广阔的世界'
  };

  const descriptions = {
    ru: 'Центр Блеск — путешествия, которые запоминаются. Подбираем необычные направления по доступным ценам.',
    en: 'Blesk Travel Center — memorable journeys. We help you find unique destinations at reasonable prices.',
    zh: 'БЛЕСК旅行中心 — 难忘的旅程。为你寻找特别且价格合理的旅行目的地。'
  };

  document.title = pageTitles[lang];

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', descriptions[lang]);

  document.documentElement.lang =
    lang === 'zh' ? 'zh-CN' : lang;

  try {
    localStorage.setItem('centerBleskLanguage', lang);
  } catch (error) {
    console.warn('Не удалось сохранить язык:', error);
  }
}

